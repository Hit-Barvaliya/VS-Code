#include<iostream>
using namespace std;
int main(){
    float a = 10.65;
    cout<<"int convert into float : "<<(int)a<<endl;
    cout<<"int convert into float : "<<int(a)<<endl;
    int b = 30;
    cout<<"float convert into int : "<<(float)b<<endl;
    cout<<"float convert into int : "<<float(b)<<endl;

    char c = 'a';
    cout<<"int convert into character : "<<(int)c<<endl;
    cout<<"int convert into character : "<<int(c)<<endl;
    return 0;
}